function suggestIndianCities(query, limit) {
  const q = String(query || "")
    .trim()
    .toLowerCase();
  const max = Number(limit) > 0 ? Number(limit) : 12;
  if (q.length < 2) return [];
  const prefix = [];
  const laterWord = [];
  for (const city of INDIAN_CITIES) {
    const lower = city.toLowerCase();
    if (lower.startsWith(q)) {
      prefix.push(city);
    } else if (lower.split(/[\s-]+/).some((part) => part.startsWith(q))) {
      laterWord.push(city);
    }
    if (prefix.length >= max) break;
  }
  return prefix.concat(laterWord).slice(0, max);
}
